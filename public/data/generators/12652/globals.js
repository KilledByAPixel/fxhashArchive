class Random {
  constructor() {
    this._gaussian_previous = false;
    this._y2 = 0;
  }
  dec = () => fxrand();
  num = (a, b) => a + (b - a) * this.dec();
  int = (a, b) => Math.floor(this.num(a, b + 1));
  idx = (arr) => arr[this.int(0, arr.length - 1)];
  max = (min, max, i) => {
    const vals = [...Array(i).keys()].map((x) => this.num(min, max));
    return Math.max(...vals);
  };
  min = (min, max, i) => {
    const vals = [...Array(i).keys()].map((x) => this.num(min, max));
    return Math.min(...vals);
  };
  shuffle(arr) {
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(this.dec() * (i + 1));
      const temp = arr[i];
      arr[i] = arr[j];
      arr[j] = temp;
    }
  }
  choose = (arr, n) => {
    const options = [...arr];
    if (n >= arr.length) return options;
    const choices = [];
    while (choices.length < n) {
      this.shuffle(options);
      choices.push(options.pop());
    }
    return choices;
  };
  norm = (mean, sd = 1) => {
    let y1, x1, x2, w;
    if (this._gaussian_previous) {
      y1 = this._y2;
      this._gaussian_previous = false;
    } else {
      do {
        x1 = this.num(-1, 1);
        x2 = this.num(-1, 1);
        w = x1 * x1 + x2 * x2;
      } while (w >= 1);
      w = Math.sqrt((-2 * Math.log(w)) / w);
      y1 = x1 * w;
      this._y2 = x2 * w;
      this._gaussian_previous = true;
    }
    const m = mean || 0;
    return y1 * sd + m || mean;
  };
}

